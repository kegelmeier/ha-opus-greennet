"""Check every MDI icon in icons.json against a pinned Home Assistant catalogue.

The catalogue is ``pylint/plugins/pylint_home_assistant/generated/mdi_icons.py``
of home-assistant/core, generated by hassfest from the pinned frontend. It is
not shipped in the ``homeassistant`` wheel, so CI checks out the reference
core commit and passes the file path here. The script needs no Home Assistant
installation and reads the catalogue with ``ast`` instead of importing it.

Usage: python script/check_icons.py <mdi_icons.py> <icons.json>
"""

from __future__ import annotations

import ast
import json
import sys
from collections.abc import Iterator
from pathlib import Path


def load_catalogue(path: Path) -> tuple[str, set[str]]:
    """Return the frontend version and the MDI names of a generated catalogue."""
    version = "unknown"
    names: set[str] = set()
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if not isinstance(node, ast.AnnAssign) or not isinstance(node.target, ast.Name):
            continue
        if node.target.id == "FRONTEND_VERSION" and node.value is not None:
            version = str(ast.literal_eval(node.value))
        elif node.target.id == "MDI_ICONS" and node.value is not None:
            names = set(ast.literal_eval(node.value))
    if not names:
        raise SystemExit(f"No MDI_ICONS set found in {path}")
    return version, names


def icon_values(value: object, path: str = "") -> Iterator[tuple[str, str]]:
    """Yield (json path, value) for every string leaf of icons.json."""
    if isinstance(value, dict):
        for key, item in value.items():
            yield from icon_values(item, f"{path}.{key}" if path else key)
    elif isinstance(value, str):
        yield path, value


def main(argv: list[str]) -> int:
    """Validate icons.json and print one line per checked icon."""
    if len(argv) != 3:
        print(__doc__)
        return 2
    version, catalogue = load_catalogue(Path(argv[1]))
    icons = json.loads(Path(argv[2]).read_text(encoding="utf-8"))
    errors = []
    checked = 0
    for path, value in icon_values(icons):
        if not value.startswith("mdi:"):
            errors.append(f"{path}: {value!r} does not start with 'mdi:'")
            continue
        checked += 1
        if value.removeprefix("mdi:") not in catalogue:
            errors.append(f"{path}: {value} is not in frontend {version}")
        else:
            print(f"ok {path}: {value}")
    print(
        f"Checked {checked} icons against {len(catalogue)} MDI names "
        f"(frontend {version})"
    )
    for error in errors:
        print(f"ERROR {error}")
    return 1 if errors or not checked else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
